"""Generate docs/finance/decision_layer_report.md from the code, so every figure is reproducible.

Run: python -B scripts/make_decision_layer_report.py
Inputs are the illustrative engine sample and the Excel-twin assumptions; nothing here is observed business data.
"""
from __future__ import annotations

import sys
from datetime import date
from decimal import Decimal as D
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from engine.cost_engine import SAMPLE, TIER_RATES, cost_part  # noqa: E402
from finance import scenarios as sc  # noqa: E402
from finance import unit_economics as ue  # noqa: E402
from finance.full_model import FinancialAssumptions  # noqa: E402

QD = date(2026, 11, 5)
MAT, MC = D("78"), D("850")
OUT = ROOT / "docs" / "finance" / "decision_layer_report.md"


def lakh(x: float | D) -> str:
    return f"{float(x) / 1e5:,.1f}"


def main() -> int:
    tiers = ue.tier_comparison(SAMPLE, TIER_RATES, MC, QD)
    base = cost_part(dict(SAMPLE), ue.make_master(MAT, MC), QD, 180000)
    shares = ue.component_shares(base)
    sens = ue.sensitivity(SAMPLE, MAT, MC, QD, 180000)
    be = ue.break_even_volume(SAMPLE, MAT, MC, QD, base["price"])
    scen = sc.run_scenarios()
    thr_release = sc.npv_break_even_win_back(FinancialAssumptions(release_wc_at_end=True))
    thr_kept = sc.npv_break_even_win_back(FinancialAssumptions(release_wc_at_end=False))
    assert be is not None and thr_release is not None and thr_kept is not None

    L = [
        "# Decision-layer report (generated)", "",
        "Generated by `scripts/make_decision_layer_report.py` from `engine/cost_engine.py`, `finance/unit_economics.py` and",
        "`finance/scenarios.py`. **All inputs are illustrative** (PRD assumption A21) and the case is hypothetical; no figure is observed.",
        "Rework cost is not modelled: the PRD formula has a rejection allowance only.", "",
        "## 1. Which volume tier is financially preferable?", "",
        "| Annual volume | Material rate | Unit cost | Price | Unit margin | Annual contribution (INR) | Preferred |",
        "|---:|---:|---:|---:|---:|---:|:---:|",
    ]
    for t in tiers:
        L.append(f"| {t['volume']:,} | {t['material_rate']} | {t['unit_cost']} | {t['price']} | {t['unit_margin']} | "
                 f"{t['annual_contribution']:,.2f} | {'yes' if t['preferred'] else ''} |")
    L += ["", "The highest tier earns most in absolute terms, but only if the customer commits to that volume. Margin is 12% of price at every tier by construction.", "",
          "## 2. Which cost line carries the most unit cost (180,000-unit tier)?", "", "| Line | Share of unit cost |", "|---|---:|"]
    L += [f"| {name} | {float(s) * 100:.1f}% |" for name, s in shares]
    L += ["", "## 3. What happens to margin if costs rise and the quoted price is held?", "",
          f"Base: unit cost {base['cost']}, price {base['price']}, margin 12.0%.", "",
          "| Shock | New unit cost | Cost change | Margin at held price | Change (points) |", "|---|---:|---:|---:|---:|"]
    L += [f"| {r['shock']} | {r['new_cost']} | {r['cost_change']} | {float(r['margin_pct_at_quoted_price']) * 100:.1f}% | {r['margin_change_points']} |" for r in sens]
    L += ["", "Machine-rate and cycle-time shocks are identical by construction (machining = cycle time x rate). Setup time is immaterial at this volume; it matters at low volume.", "",
          "## 4. At what volume does the quoted price cover full unit cost?", "",
          f"At the quoted price of {base['price']}, full unit cost (including setup spread over volume) is covered from **{be:,} pieces a year**. "
          "Zero margin is the break-even here because the engine's cost already includes overhead and rejection.", "",
          "## 5. Investment scenarios (Python twin of the Excel model)", "",
          "| Scenario | Win-back | NPV (INR lakh) | IRR | Payback (years) | Peak funding (INR lakh) |", "|---|---:|---:|---:|---:|---:|"]
    for r in scen:
        irr = f"{r['irr'] * 100:.1f}%" if r["irr"] is not None else "n/a"
        pb = f"{r['payback_years']:.2f}" if r["payback_years"] is not None else "n/a"
        L.append(f"| {r['scenario']} | {r['win_back'] * 100:.1f}% | {lakh(r['npv'])} | {irr} | {pb} | {lakh(r['peak_funding'])} |")
    L += ["", *[f"- **{r['scenario']}**: {r['note']}" for r in scen], "",
          "## 6. Decision thresholds", "",
          f"- Win-back at which three-year NPV is zero: **{thr_release * 100:.1f}%** with working capital released in year 3; "
          f"**{thr_kept * 100:.1f}%** if it is never released.",
          "- This differs from the 11.6% figure elsewhere in the pack, which is the win-back that recovers the fee and run cost within one year. "
          "They answer different questions: three-year value versus one-year recovery.",
          "- Both depend on the assumed win-back, which no one has observed. A pilot should measure it before the build.", ""]
    OUT.write_text("\n".join(L), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

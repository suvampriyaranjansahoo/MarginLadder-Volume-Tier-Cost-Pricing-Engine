"""Ratios from the real filing, and a reality check of the MarginLadder case assumptions against them.

Run: python -m realdata.benchmark   (writes docs/finance/real_company_benchmark.md)
"""
from __future__ import annotations

from datetime import date
from pathlib import Path

from engine.cost_engine import MASTER, SAMPLE, cost_part
from finance.full_model import FinancialAssumptions, financials
from realdata import bharat_forge_fy26 as bf

LAKH_PER_CRORE = 100.0
DAYS = 365


def crore(lakh: float) -> float:
    return lakh / LAKH_PER_CRORE


def metrics() -> dict[str, float]:
    p, b, c = bf.PNL, bf.BALANCE_SHEET, bf.CASH_FLOW
    rev = p["revenue_from_operations"]
    # EBITDA is not a line in the filing: PBT before exceptionals + finance cost + D&A - other income.
    ebitda = p["profit_before_exceptional_and_tax"] + p["finance_costs"] + p["depreciation_and_amortisation"] - p["other_income"]
    material = p["cost_of_materials_consumed"] + p["purchases_of_stock_in_trade"] + p["changes_in_inventories"]
    debt = b["borrowings_non_current"] + b["borrowings_current"]
    liquid = b["cash_and_cash_equivalents"] + b["other_bank_balances"] + b["current_investments"]
    net_debt = debt - liquid
    shares = p["paid_up_equity_share_capital"] / p["face_value_per_share_inr"]      # lakh shares
    mcap = shares * bf.SHARE_PRICE_INR                                               # INR lakh
    free_cash = c["cash_from_operations_after_tax"] - c["purchase_of_ppe"]
    net_margin = p["total_profit_for_period"] / rev
    turnover = rev / b["total_assets"]
    leverage = b["total_assets"] / b["total_equity"]
    dso = b["trade_receivables_current"] / rev * DAYS
    dio = b["inventories"] / material * DAYS
    dpo = b["trade_payables_current"] / material * DAYS
    return {
        "revenue": rev, "ebitda": ebitda, "ebitda_margin": ebitda / rev,
        "reported_ebitda_gap_pct": (ebitda - bf.REPORTED_CONSOLIDATED_EBITDA_CRORE * LAKH_PER_CRORE)
        / (bf.REPORTED_CONSOLIDATED_EBITDA_CRORE * LAKH_PER_CRORE),
        "pbt_margin": p["profit_before_tax"] / rev, "effective_tax_rate": p["total_tax"] / p["profit_before_tax"],
        "material_share_of_revenue": material / rev,
        "employee_share_of_revenue": p["employee_benefit_expense"] / rev,
        "other_expense_share_of_revenue": p["other_expenses"] / rev,
        "debt": debt, "liquid_assets": liquid, "net_debt": net_debt,
        "debt_to_equity": debt / b["total_equity"], "net_debt_to_ebitda": net_debt / ebitda,
        "net_margin": net_margin, "asset_turnover": turnover, "equity_multiplier": leverage,
        "roe": net_margin * turnover * leverage,
        "dso_days": dso, "dio_days": dio, "dpo_days": dpo, "cash_conversion_days": dso + dio - dpo,
        "capex": c["purchase_of_ppe"], "capex_to_revenue": c["purchase_of_ppe"] / rev,
        "cfo": c["cash_from_operations_after_tax"], "cfo_to_ebitda": c["cash_from_operations_after_tax"] / ebitda,
        "free_cash_flow": free_cash, "fcf_to_profit": free_cash / p["total_profit_for_period"],
        "market_cap": mcap, "enterprise_value": mcap + net_debt,
        "ev_to_ebitda": (mcap + net_debt) / ebitda, "price_to_earnings": bf.SHARE_PRICE_INR / p["eps_basic_inr"],
    }


def balance_sheet_balances() -> bool:
    b = bf.BALANCE_SHEET
    return abs(b["total_assets"] - (b["total_equity"] + b["total_liabilities"])) < 0.01


def segment_margins() -> dict[str, float]:
    return {k: v["result"] / v["revenue"] for k, v in bf.SEGMENTS.items()}


def engine_sample_material_share() -> float:
    """Material cost as a share of selling price for the case's sample part, from the costing engine itself."""
    r = cost_part(SAMPLE, MASTER, date(2026, 11, 5), 180000)
    return float(r["net_material"] / r["price"])


def working_capital_stress() -> list[dict[str, float | None]]:
    """Re-run the case's 3-year financials with working-capital days taken from the real filing."""
    m = metrics()
    rows = []
    for label, days in (("Case assumption", 45), ("Real receivable days (DSO)", round(m["dso_days"])),
                        ("Real cash conversion cycle", round(m["cash_conversion_days"]))):
        f = financials(0.25, FinancialAssumptions(working_capital_days=days))
        rows.append({"case": label, "days": days, "irr": f["irr"], "payback_years": f["payback_years"]})
    return rows


